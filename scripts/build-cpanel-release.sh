#!/usr/bin/env bash
# Builds a deployable copy of the current commit for cPanel, where composer and npm can't run:
# production vendor/ and public/build/ are committed onto a deploy branch, which cPanel's Git Version
# Control pulls. Source branches never carry built files.
#
#   composer release                          # build HEAD onto cpanel-deploy and push it
#   composer release:testing                  # ...onto cpanel-deploy-dev
#   scripts/build-cpanel-release.sh           # build and commit locally, no push
#
# Env:
#   TARGET_BRANCH  deploy branch to commit to (default cpanel-deploy; testing uses cpanel-deploy-dev)
#   APP_PATH       where that branch is cloned on the server; written into the branch's .cpanel.yml
#                  (default /home/subaorac/public_html/subaora.com/repositories/kh-backend)
#   REMOTE         default origin
set -euo pipefail

cd "$(dirname "$0")/.."
root="$(pwd)"
target="${TARGET_BRANCH:-cpanel-deploy}"
remote="${REMOTE:-origin}"
app_path="${APP_PATH:-/home/subaorac/public_html/subaora.com/repositories/kh-backend}"
app_path="${app_path%/}"
case "$app_path" in
    /*) ;;
    *) echo "APP_PATH must be an absolute path on the server, got: $app_path" >&2; exit 1 ;;
esac
push=false
[ "${1:-}" = "--push" ] && push=true

if [ -n "$(git status --porcelain)" ]; then
    echo "Commit or stash your changes first: the release is built from HEAD." >&2
    exit 1
fi
sha="$(git rev-parse --short HEAD)"
tmp="$(mktemp -d)"
build="$tmp/build"
wt="$tmp/worktree"
cleanup() {
    git -C "$root" worktree remove --force "$wt" >/dev/null 2>&1 || true
    rm -rf "$tmp"
}
trap cleanup EXIT

echo "==> Exporting $sha"
mkdir -p "$build"
git archive HEAD | tar -x -C "$build"

cd "$build"
# Only for build-time artisan calls (package discovery, Wayfinder); never shipped.
cp .env.example .env
php -r 'file_put_contents(".env", preg_replace("/^APP_ENV=.*/m", "APP_ENV=production", file_get_contents(".env")));'

echo "==> composer install (production)"
composer install --no-dev --optimize-autoloader --no-interaction --no-progress --quiet
php artisan key:generate --force --quiet

echo "==> npm build"
npm ci --no-audit --no-fund --loglevel=error
npm run build

min_php="$(grep -o 'PHP_VERSION_ID >= [0-9]*' vendor/composer/platform_check.php | grep -o '[0-9]*$' || echo 0)"
# PHP extensions required by the app and its production packages.
exts="$(php -r '
    $lock = json_decode(file_get_contents("composer.lock"), true);
    $reqs = array_keys(json_decode(file_get_contents("composer.json"), true)["require"] ?? []);
    foreach ($lock["packages"] as $p) { $reqs = array_merge($reqs, array_keys($p["require"] ?? [])); }
    $exts = array_unique(array_map(fn ($r) => substr($r, 4), array_filter($reqs, fn ($r) => str_starts_with($r, "ext-"))));
    sort($exts);
    echo implode(" ", $exts);
')"

rm -rf node_modules .env bootstrap/cache/*.php public/hot storage/logs/*.log

# cPanel runs this after "Deploy HEAD Commit". The path differs per environment, so each deploy
# branch gets its own copy; scripts/cpanel-deploy.sh finds the app folder from its own location.
cat > .cpanel.yml <<YAML
---
# Generated by scripts/build-cpanel-release.sh for $target. Do not edit on this branch.
deployment:
    tasks:
        - /bin/bash $app_path/scripts/cpanel-deploy.sh
YAML
cd "$root"

echo "==> Committing to $target (deploys from $app_path)"
# Fetch into an explicit ref: shallow CI checkouts don't track other branches. The remote copy wins
# over a stale local branch, so the push is always a fast-forward.
git fetch --quiet "$remote" "+refs/heads/$target:refs/remotes/$remote/$target" 2>/dev/null || true
if git show-ref --verify --quiet "refs/remotes/$remote/$target"; then
    git worktree add --quiet --force -B "$target" "$wt" "$remote/$target"
elif git show-ref --verify --quiet "refs/heads/$target"; then
    git worktree add --quiet --force "$wt" "$target"
else
    git worktree add --quiet --orphan -b "$target" "$wt"
fi

cd "$wt"
git rm -rq --ignore-unmatch . >/dev/null
rsync -a --delete --exclude .git "$build/" "$wt/"
git add -A
# Ignored on source branches, required on the server.
git add -f vendor public/build
if git diff --cached --quiet; then
    # Same build as last time (e.g. a re-run); nothing to commit, and the push below is a no-op.
    echo "    No changes since $(git log --oneline -1)"
else
    git commit --quiet -m "Release $sha to $target" -m "Built from $(git -C "$root" rev-parse HEAD) with production dependencies; deploys from $app_path."
    echo "    $(git log --oneline -1)"
fi

if $push; then
    git push --quiet "$remote" "$target"
    echo "==> Pushed $remote/$target. To deploy: cPanel > Git Version Control > Manage > Pull or Deploy > Update from Remote, then Deploy HEAD Commit."
else
    echo "==> Not pushed. Run: git push $remote $target"
fi

printf '\nServer needs PHP >= %s.%s.%s with extensions: %s\n' \
    "$((min_php / 10000))" "$((min_php / 100 % 100))" "$((min_php % 100))" "${exts:-see composer check-platform-reqs}"
